export function detectLanguage() {
  const settings = NativeModules.SettingsManager?.settings;
  const locale = settings?.AppleLocale ?? settings?.AppleLanguages?.[0] ?? '';
  return String(locale).toLowerCase().startsWith('en') ? 'en' : 'tr';
}

